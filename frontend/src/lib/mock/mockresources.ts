export function resourcesFor(group: string): Array<{ key: string; value: string }> {
  const name = (group ?? '').split('/').filter((part) => part !== '').pop() ?? '';
  const values = RESOURCES[name] ?? {};

  return Object.entries(values).map(([key, value]) => ({ key, value }));
}
